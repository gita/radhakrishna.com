#!/usr/bin/env node
/**
 * Generates lib/daily-verses.ts from the Ved Vyas Foundation's own Gita dataset
 * (github.com/gita/gita), so every verse on the site is pulled verbatim from a
 * named translation rather than written from memory.
 *
 * Only the SELECTION below is editorial. The wording, chapter and verse always
 * come from the dataset, which is what keeps us honest (docs/01 §6).
 *
 * Usage: node scripts/build-daily-verses.mjs
 */
import { writeFileSync } from "node:fs";

const TRANSLATOR = "Swami Sivananda";

// Curated for daily darshan: devotion, surrender, steadiness and the nature of
// the Lord. Deliberately skips battlefield logistics and the enumerative
// chapters, which do not serve as a morning verse.
const PICKS = [
  [2, 47], [2, 48], [2, 50], [2, 56], [2, 62], [2, 70], [2, 71],
  [3, 19], [3, 30], [3, 35],
  [4, 7], [4, 8], [4, 11], [4, 18], [4, 24], [4, 38], [4, 39],
  [5, 10], [5, 18], [5, 21], [5, 29],
  [6, 5], [6, 19], [6, 22], [6, 26], [6, 29], [6, 30], [6, 32], [6, 35],
  [7, 7], [7, 8], [7, 14], [7, 16], [7, 17], [7, 19], [7, 25],
  [8, 5], [8, 7], [8, 14], [8, 15],
  [9, 2], [9, 13], [9, 14], [9, 17], [9, 22], [9, 26], [9, 27], [9, 29],
  [9, 30], [9, 31], [9, 34],
  [10, 8], [10, 9], [10, 10], [10, 11], [10, 20], [10, 41],
  [11, 43], [11, 44], [11, 54], [11, 55],
  [12, 6], [12, 8], [12, 13], [12, 14], [12, 15], [12, 17], [12, 20],
  [13, 27], [13, 28],
  [14, 26], [14, 27],
  [15, 5], [15, 6], [15, 15], [15, 19],
  [16, 1], [16, 2], [16, 3],
  [17, 3],
  [18, 46], [18, 54], [18, 55], [18, 61], [18, 62], [18, 65], [18, 66],
  [18, 78],
];

const [verses, translations] = await Promise.all([
  fetch("https://raw.githubusercontent.com/gita/gita/main/data/verse.json").then((r) => r.json()),
  fetch("https://raw.githubusercontent.com/gita/gita/main/data/translation.json").then((r) => r.json()),
]);

const verseById = new Map(verses.map((v) => [v.id, v]));
const byRef = new Map();
for (const v of verses) byRef.set(`${v.chapter_number}.${v.verse_number}`, v);

const englishByVerseId = new Map();
for (const t of translations) {
  if (t.lang !== "english" || t.authorName !== TRANSLATOR) continue;
  englishByVerseId.set(t.verse_id, t.description);
}

const clean = (s) =>
  String(s)
    .replace(/\s+/g, " ")
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/—/g, ", ")
    .trim();

const out = [];
const missing = [];
for (const [ch, vn] of PICKS) {
  const v = byRef.get(`${ch}.${vn}`);
  if (!v) { missing.push(`${ch}.${vn} (no such verse)`); continue; }
  const text = englishByVerseId.get(v.id);
  if (!text) { missing.push(`${ch}.${vn} (no ${TRANSLATOR} translation)`); continue; }
  const quote = clean(text);
  // A daily card should be readable at a glance.
  if (quote.length > 320) { missing.push(`${ch}.${vn} (too long: ${quote.length})`); continue; }
  out.push({ quote, source: `Bhagavad Gita ${ch}.${vn}` });
}

if (missing.length) {
  console.log(`Skipped ${missing.length}:`);
  for (const m of missing) console.log("  " + m);
}

const file = `// GENERATED by scripts/build-daily-verses.mjs. Do not edit by hand.
// Every quote is taken verbatim from the ${TRANSLATOR} translation in the
// foundation's own dataset (github.com/gita/gita), so nothing here is written
// from memory. Re-run the script to change the selection.

export type DailyVerse = { quote: string; source: string };

export const TRANSLATOR = ${JSON.stringify(TRANSLATOR)};

export const DAILY_VERSES: DailyVerse[] = ${JSON.stringify(out, null, 2)};
`;

writeFileSync("lib/daily-verses.ts", file);
console.log(`Wrote lib/daily-verses.ts with ${out.length} verses (${TRANSLATOR}).`);
